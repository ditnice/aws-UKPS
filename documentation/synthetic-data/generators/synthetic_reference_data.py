ARCHIVED_BNF_CHAPTERS = {"9.4"}


def _hierarchy(entries, archived=frozenset()):
    rows = []
    for order, (code, label) in enumerate(entries, start=1):
        parent = code.rsplit(".", 1)[0] if "." in code else None
        rows.append({
            "code": code,
            "label": label,
            "parentCode": parent,
            "displayOrder": order,
            "isArchived": code in archived,
        })
    return rows


def _flat(labels):
    return [{"label": label, "displayOrder": order} for order, label in enumerate(labels, start=1)]


